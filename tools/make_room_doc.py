def full(g, one_door=False):
    n = len(g)
    rows = []
    for i in range(-1, n + 1):
        r = ''
        for j in range(-1, n + 1):
            edge_i, edge_j = i in (-1, n), j in (-1, n)
            if edge_i or edge_j:
                door = (edge_i and j in (8, 9)) or (edge_j and i in (8, 9))
                if one_door: door = (i == n and j in (8, 9))
                r += 'D' if door and not (edge_i and edge_j) else 'W'
            else:
                r += g[i][j]
        rows.append(' '.join(r))
    return '\n'.join(rows)

